% Engine-neutral regression cases. Load after examples/portable_json.pl.
json_test_assert(Goal) :- (call(Goal) -> true ; throw(json_test_failed(Goal))).
json_test_reject(Text) :- atom_chars(Text,Cs), json_test_reject_chars(Cs).
json_test_reject_chars(Cs) :- catch((portable_json_chars(_,Cs),R=accepted),error(syntax_error(json),_),R=rejected),json_test_assert(R==rejected).
json_test_roundtrip(Text,Expected) :- atom_chars(Text,Cs),findall(V,portable_json_chars(V,Cs),[Value]),json_test_assert(Value=Expected),findall(Out,portable_json_chars(Value,Out),[Encoded]),portable_json_chars(Again,Encoded),json_test_assert(Again==Value).
portable_json_regression :-
    json_test_roundtrip('{}',json([])),
    json_test_roundtrip('[]',[]),
    json_test_roundtrip('""',string([])),
    json_test_roundtrip('"[]"',string([91, 93])),
    json_test_roundtrip('{"[]":[],"":true,"x":"true","x":null}',json([string([91,93])=[],string([])= @(true),string([120])=string([116,114,117,101]),string([120])= @(null)])),
    json_test_roundtrip('[true,false,null,-12,0,1.5,1e2]',[@(true),@(false),@(null),-12,0,1.5,100.0]),
    json_test_roundtrip('"\\"\\\\\\/\\b\\f\\n\\r\\t"',string([34, 92, 47, 8, 12, 10, 13, 9])),
    json_test_roundtrip('"\\u00e5\\uD83D\\uDE00"',string([229, 128512])),
    json_test_roundtrip('{"nested":[{},["hello",false]]}',json([string([110, 101, 115, 116, 101, 100])=[json([]),[string([104, 101, 108, 108, 111]),@(false)]]])),
    json_test_roundtrip('"\\u0000"',string([0])),
    json_test_reject(''),
    json_test_reject(' '),
    json_test_reject('['),
    json_test_reject('{'),
    json_test_reject('[1,]'),
    json_test_reject('{"a":1,}'),
    json_test_reject('{"a" 1}'),
    json_test_reject('true false'),
    json_test_reject('01'),
    json_test_reject('-01'),
    json_test_reject('+1'),
    json_test_reject('1.'),
    json_test_reject('1e'),
    json_test_reject('1e+'),
    json_test_reject('NaN'),
    json_test_reject('Infinity'),
    json_test_reject('"\\x00"'),
    json_test_reject('"\\uD800"'),
    json_test_reject('"\\uDC00"'),
    json_test_reject('"\\uD800\\u0041"'),
    json_test_reject_chars(['"','\n','"']),
    json_test_reject('"unterminated'),
    json_test_assert(\+ portable_json_value(json([x=1]))),
    json_test_assert(\+ portable_json_value(string([ab]))),
    json_test_assert(\+ portable_json_value(_)),
    json_test_assert(portable_json_get(json([string([120])=1,string([120])=2]),x,1)),
    json_test_assert(\+ portable_json_get(json([]),x,_)),
    json_test_assert(\+ portable_json_get(json([string([120])=1,string([120])=2]),x,2)),
    catch((portable_json_chars(_, _),Error=missing),error(instantiation_error,_),Error=instantiation_error),
    json_test_assert(Error==instantiation_error).
